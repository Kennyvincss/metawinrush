// Generates supabase/migrations/0002_catalog_seed.sql from the TypeScript catalogs so the
// database and the game share one source of truth. Run: npm run db:seed-sql
import { writeFileSync } from "node:fs";
import { ACHIEVEMENTS } from "../src/lib/data/achievements";
import { CITIES } from "../src/lib/data/cities";
import { COSMETICS } from "../src/lib/data/cosmetics";
import { ALL_MISSIONS } from "../src/lib/data/missions";

const q = (v: string | number | boolean | null | undefined) =>
  v === null || v === undefined ? "null" : typeof v === "string" ? `'${v.replace(/'/g, "''")}'` : String(v);

const lines: string[] = ["-- Generated by scripts/generate-seed.ts — do not edit by hand.", ""];

lines.push("insert into public.cities (id, name, theme, unlock_type, unlock_value, sort) values");
lines.push(
  CITIES.map((c, i) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.theme)}, ${q(c.unlock.type)}, ${"value" in c.unlock ? c.unlock.value : 0}, ${i})`).join(",\n") +
    "\non conflict (id) do update set name = excluded.name, theme = excluded.theme, unlock_type = excluded.unlock_type, unlock_value = excluded.unlock_value, sort = excluded.sort;",
  "",
);

lines.push("insert into public.characters (id, slot, name, rarity, price, unlock_level, reward_only) values");
lines.push(
  COSMETICS.map((c) => `  (${q(c.id)}, ${q(c.slot)}, ${q(c.name)}, ${q(c.rarity)}, ${c.price}, ${q(c.unlockLevel ?? null)}, ${!!c.rewardOnly})`).join(",\n") +
    "\non conflict (id) do update set slot = excluded.slot, name = excluded.name, rarity = excluded.rarity, price = excluded.price, unlock_level = excluded.unlock_level, reward_only = excluded.reward_only;",
  "",
);

lines.push("insert into public.missions (id, kind, title, description, metric, target, city_id, reward_coins, reward_xp) values");
lines.push(
  ALL_MISSIONS.map((m) => `  (${q(m.id)}, ${q(m.kind)}, ${q(m.title)}, ${q(m.description)}, ${q(m.metric)}, ${m.target}, ${q(m.city ?? null)}, ${m.reward.coins}, ${m.reward.xp})`).join(",\n") +
    "\non conflict (id) do update set kind = excluded.kind, title = excluded.title, description = excluded.description, metric = excluded.metric, target = excluded.target, city_id = excluded.city_id, reward_coins = excluded.reward_coins, reward_xp = excluded.reward_xp;",
  "",
);

lines.push("insert into public.achievements (id, title, description, icon, target, reward_coins, reward_xp) values");
lines.push(
  ACHIEVEMENTS.map((a) => `  (${q(a.id)}, ${q(a.title)}, ${q(a.description)}, ${q(a.icon)}, ${a.target}, ${a.reward.coins}, ${a.reward.xp})`).join(",\n") +
    "\non conflict (id) do update set title = excluded.title, description = excluded.description, icon = excluded.icon, target = excluded.target, reward_coins = excluded.reward_coins, reward_xp = excluded.reward_xp;",
  "",
);

writeFileSync(new URL("../supabase/migrations/0002_catalog_seed.sql", import.meta.url), lines.join("\n"));
console.log("wrote supabase/migrations/0002_catalog_seed.sql");
